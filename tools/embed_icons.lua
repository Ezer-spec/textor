#!/usr/bin/env lua
-- Packs assets/icons/*.svg and assets/icons/ui/*.svg into ui/file_icons_data.hxx
-- (the icons live inside the binary).
--
-- Run from the project root after adding or changing an icon:
--     lua tools/embed_icons.lua
--
-- assets/icons/*.svg     language icons, the name is the file name:  "lua"
-- assets/icons/ui/*.svg  icons of the editor itself, "ui_" + file name:  "ui_search"

local function svg_files(dir)
    local files = {}
    local ls = io.popen("LC_ALL=C ls " .. dir .. "/*.svg 2>/dev/null")
    for line in ls:lines() do files[#files + 1] = line end
    ls:close()
    return files
end

-- Makes the SVG one short line: no xml header, comments, titles, extra spaces
local function minify(svg)
    svg = svg:gsub("<%?xml.-%?>", "")
    svg = svg:gsub("<!DOCTYPE.->", "")
    svg = svg:gsub("<!%-%-.-%-%->", "")
    svg = svg:gsub("<title>.-</title>", "")
    svg = svg:gsub("<desc>.-</desc>", "")
    svg = svg:gsub("%s+", " ")
    svg = svg:gsub(">%s+<", "><")
    return (svg:gsub("^%s+", ""):gsub("%s+$", ""))
end

local jobs = {}   -- { icon name, file path }
for _, path in ipairs(svg_files("assets/icons")) do
    jobs[#jobs + 1] = { path:match("([^/]+)%.svg$"), path }
end
for _, path in ipairs(svg_files("assets/icons/ui")) do
    jobs[#jobs + 1] = { "ui_" .. path:match("([^/]+)%.svg$"), path }
end

local out = {
    "// Generated by tools/embed_icons.lua - do not edit by hand.",
    "#ifndef FILE_ICONS_DATA_HXX",
    "#define FILE_ICONS_DATA_HXX",
    "",
    "struct EmbeddedIcon { const char *name; const char *svg; };",
    "static const EmbeddedIcon k_embedded_icons[] = {",
}
for _, job in ipairs(jobs) do
    local name, path = job[1], job[2]
    local file = assert(io.open(path, "rb"))
    local svg = minify(file:read("a"))
    file:close()
    assert(not svg:find(')SVG"', 1, true), path .. ": contains the text )SVG\"")
    out[#out + 1] = string.format('    {"%s", R"SVG(%s)SVG"},', name, svg)
end
out[#out + 1] = "    {nullptr, nullptr}"
out[#out + 1] = "};"
out[#out + 1] = ""
out[#out + 1] = "#endif"
out[#out + 1] = ""

local f = assert(io.open("ui/file_icons_data.hxx", "wb"))
f:write(table.concat(out, "\n"))
f:close()
print("ok: " .. #jobs .. " icons")
